#!/usr/bin/env python3
"""
Convert a raw binary into a word-oriented $readmemh image.

Why not `objcopy -O verilog --verilog-data-width=4` directly: objcopy's `@`
records carry *byte* addresses, but $readmemh reads them as indices into the
target array. For a 32-bit-wide memory that is a factor-of-four error on every
section after the first, which shows up as code landing at the wrong address
rather than as an error. Producing the image here keeps the indexing explicit.

Input is expected to start at the memory's base address, which is what
`objcopy -O binary` gives for an image linked from 0.

When a size is given the output is padded to fill the whole memory. That lets
`$readmemh` be the only initialiser: a synthesis tool will not unroll an
8192-iteration zeroing loop (Gowin caps loops at 2000), and leaving the tail
uninitialised would put X into simulation.

Usage:  bin_to_wordhex.py <in.bin> <out.hex> [size_bytes]
"""

import sys


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)

    src, dst = sys.argv[1], sys.argv[2]
    limit = int(sys.argv[3]) if len(sys.argv) > 3 else None

    data = open(src, 'rb').read()
    payload = len(data)

    if limit is not None and len(data) > limit:
        sys.exit(f"bin_to_wordhex: image is {len(data)} bytes, "
                 f"memory holds {limit}")

    # Pad to a whole number of 32-bit words, then out to the full memory size
    if len(data) % 4:
        data += b'\x00' * (4 - len(data) % 4)
    if limit is not None:
        data += b'\x00' * (limit - len(data))

    with open(dst, 'w') as f:
        f.write("// generated by scripts/bin_to_wordhex.py\n")
        f.write(f"// {len(data)} bytes, {len(data)//4} words, "
                f"one 32-bit little-endian word per line\n")
        f.write(f"// program occupies {payload} bytes\n")
        for i in range(0, len(data), 4):
            word = int.from_bytes(data[i:i+4], 'little')
            f.write(f"{word:08X}\n")

    print(f"bin_to_wordhex: {dst}, {len(data)//4} words "
          f"({payload} bytes of program)")


if __name__ == "__main__":
    main()
